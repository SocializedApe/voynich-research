"""d1_parsefix.py -- the Voynich-side headline statistics on the September parse and on the fixed parse.

The parse defect (NOTES.md section 0): parse_ivtff.py deleted the '<->' marks between glyphs (drawing interruptions
that behave like word spaces), gluing false compounds, and dropped '{..}' ligature groups with their glyphs.
`parse_ivtff.py --fixed` repairs both (data/ZL3b-n.fixed.words.tsv). This script recomputes, on both TSVs, the
Voynich numbers that need no comparison corpus, with the September functions themselves (a2_wordstats,
a3_wordgrammar) and one shared character-entropy routine:
  tokens and types, Zipf slope ranks 1-1000, hapax share of types, word length mean and variance (raw EVA and
  a2's merged glyphs), adjacent identical and edit-1 pairs, a3's pair-order violation and best glyph order,
  h1 and h2 of the letter stream without spaces (raw EVA and a3's merged glyphs), and the same split by Currier A/B.
The comparison corpora (Gutenberg books, the frozen Italian sample) are not needed and not touched.

usage (from targets/voynich): python d1_parsefix.py  -> results/d1_parsefix.json and .md
"""
import collections, json, math, os, sys
sys.stdout.reconfigure(encoding='utf-8')
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import a2_wordstats as a2
import a3_wordgrammar as a3

TSVS = {'september': os.path.join(HERE, 'data', 'ZL3b-n.words.tsv'),
        'fixed': os.path.join(HERE, 'data', 'ZL3b-n.fixed.words.tsv')}


def H(c):
    n = sum(c.values())
    return -sum(v / n * math.log2(v / n) for v in c.values() if v)


def char_h(lines_of_symbol_lists):
    """h1 and h2 = H(X2|X1) of the symbol stream, words concatenated within a line without spaces, no pair across
    lines (the convention 'no spaces' of NOTES.md 4.1)."""
    uni = collections.Counter(); bi = collections.Counter()
    for syms in lines_of_symbol_lists:
        uni.update(syms); bi.update(zip(syms, syms[1:]))
    first = collections.Counter(a for a, _ in bi.elements())
    return H(uni), H(bi) - H(first)


def stats(path, lang=None):
    lines = a2.load_voynich(path)
    if lang:
        lines = [l for l in lines if l['lang'] == lang]
    r = a2.analyse_voynich(lines, os.path.basename(path))
    out = {'tokens': r['tokens'], 'types': r['zipf']['types'], 'zipf_1_1000': r['zipf']['zipf_slope_1_1000'],
           'hapax_type_frac': r['zipf']['hapax_type_frac'],
           'len_raw_mean': r['wordlength_raw']['mean'], 'len_raw_var': r['wordlength_raw']['variance'],
           'len_merged_mean': r['wordlength_merged']['mean'], 'len_merged_var': r['wordlength_merged']['variance'],
           'adjacent_identical_pct': r['repetition_raw']['identical_pct'],
           'adjacent_identical_ratio': r['repetition_raw']['identical_ratio_obs_over_shuffled'],
           'adjacent_ed1_pct': r['repetition_raw']['ed1_pct']}
    raw_lines = [[c for w in l['words'] for c in w] for l in lines]
    mrg_lines = [[c for w in l['words'] for c in a3.merge_eva(w)] for l in lines]
    out['h1_raw'], out['h2_raw'] = char_h(raw_lines)
    out['h1_merged'], out['h2_merged'] = char_h(mrg_lines)
    toks = [a3.merge_eva(w) for l in lines for w in l['words'] if not (set(w) - a3.EVA_OK)]
    prec, freq, typec = a3.precedence_counts(toks)
    order, vw, tw = a3.best_order(prec, [s for s, _ in freq.most_common()])
    out['pair_violation_frac'] = vw / tw
    out['order'] = ' '.join(a3.symname(s) for s in order)
    return out


def main():
    R = {}
    for tag, path in TSVS.items():
        for lang in (None, 'A', 'B'):
            key = f'{tag}{"" if lang is None else "_" + lang}'
            print('...', key, flush=True)
            R[key] = stats(path, lang)
    json.dump(R, open(os.path.join(HERE, 'results', 'd1_parsefix.json'), 'w', encoding='utf-8'), indent=1)
    rows = ['tokens', 'types', 'zipf_1_1000', 'hapax_type_frac', 'len_raw_mean', 'len_raw_var', 'len_merged_mean',
            'len_merged_var', 'adjacent_identical_pct', 'adjacent_identical_ratio', 'adjacent_ed1_pct', 'h1_raw',
            'h2_raw', 'h1_merged', 'h2_merged', 'pair_violation_frac']
    md = ['# d1: Voynich statistics, September parse against fixed parse', '',
          'Generated by `d1_parsefix.py`. Fixed parse = `parse_ivtff.py --fixed` (`<->` as a word break, `{..}` glyphs kept).',
          '', '| statistic | Sept. all | fixed all | Sept. A | fixed A | Sept. B | fixed B |', '|---|---|---|---|---|---|---|']
    for k in rows:
        vals = [R[t][k] for t in ('september', 'fixed', 'september_A', 'fixed_A', 'september_B', 'fixed_B')]
        md.append(f'| {k} | ' + ' | '.join(f'{v:.4f}' if isinstance(v, float) else str(v) for v in vals) + ' |')
    md += ['', f"Best glyph order, September: {R['september']['order']}", f"Best glyph order, fixed: {R['fixed']['order']}"]
    open(os.path.join(HERE, 'results', 'd1_parsefix.md'), 'w', encoding='utf-8').write('\n'.join(md) + '\n')
    print('\n'.join(md))


if __name__ == '__main__':
    main()
